def translate_crop_name(crop_name: str, lang_code: str) -> str:
    """Translates crop name into target language if available."""
    if lang_code == "en" or not lang_code:
        return crop_name
    translations = CROP_TRANSLATIONS.get(crop_name, {})
    return translations.get(lang_code, crop_name)

